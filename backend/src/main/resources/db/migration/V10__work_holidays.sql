-- =====================================================================
-- V10: work holidays.
-- Sundays stop being a fixed day off: the owner marks any date as a holiday instead,
-- and attendance can't be recorded on a marked date. Additive: one new table.
-- =====================================================================

CREATE TABLE work_holidays (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    holiday_date DATE        NOT NULL,
    note         VARCHAR(200),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by   BIGINT REFERENCES app_users (id),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_work_holidays_date UNIQUE (holiday_date),
    CONSTRAINT ck_work_holidays_note CHECK (note IS NULL OR btrim(note) <> '')
);
