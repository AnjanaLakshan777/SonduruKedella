-- FIFO inventory costing (replaces the moving weighted average). Additive: no existing row is updated
-- or deleted, so the append-only ledger and everything already posted to projects stay exactly as they were.
--
--   stock_cost_layers       one row per batch of stock that came in (a receipt, a positive adjustment),
--                           with what is still left of it. Issues use up the oldest layer first.
--   stock_cost_allocations  which layers each issue / negative adjustment drew from, and how much of
--                           that has come back on a return. Append-only, like the ledger.

-- Which method priced each movement. Rows already in the ledger were priced at the weighted average:
-- ADD COLUMN with a default fills them without an UPDATE (so trg_stock_movements_immutable never
-- fires), then the default becomes FIFO for everything posted from now on.
ALTER TABLE stock_movements ADD COLUMN costing_method VARCHAR(10) NOT NULL DEFAULT 'WAC';
ALTER TABLE stock_movements ALTER COLUMN costing_method SET DEFAULT 'FIFO';
ALTER TABLE stock_movements ADD CONSTRAINT ck_stock_movements_costing_method CHECK (costing_method IN ('WAC', 'FIFO'));

-- Targets for the composite keys below, so a layer or an allocation can only belong to a movement of
-- the same material.
ALTER TABLE stock_movements ADD CONSTRAINT uq_stock_movements_id_material UNIQUE (id, material_id);

CREATE TABLE stock_cost_layers (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id        BIGINT        NOT NULL REFERENCES materials (id),
    -- the movement that brought this stock in; for LEGACY_BALANCE, the last movement before FIFO
    source_movement_id BIGINT        NOT NULL,
    origin             VARCHAR(20)   NOT NULL,
    layer_date         DATE          NOT NULL,
    original_quantity  NUMERIC(14,3) NOT NULL,
    unit_cost          NUMERIC(15,4) NOT NULL,
    original_cost      NUMERIC(15,2) NOT NULL,
    remaining_quantity NUMERIC(14,3) NOT NULL,
    remaining_value    NUMERIC(15,2) NOT NULL,
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by         BIGINT REFERENCES app_users (id),
    updated_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version            BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uq_stock_cost_layers_source UNIQUE (source_movement_id),
    CONSTRAINT uq_stock_cost_layers_id_material UNIQUE (id, material_id),
    CONSTRAINT fk_stock_cost_layers_source FOREIGN KEY (source_movement_id, material_id)
        REFERENCES stock_movements (id, material_id),
    CONSTRAINT ck_stock_cost_layers_origin CHECK (origin IN ('RECEIPT', 'ADJUSTMENT', 'LEGACY_BALANCE', 'LEGACY_RETURN')),
    CONSTRAINT ck_stock_cost_layers_quantity CHECK (
        original_quantity > 0 AND remaining_quantity >= 0 AND remaining_quantity <= original_quantity),
    CONSTRAINT ck_stock_cost_layers_cost CHECK (
        unit_cost >= 0 AND original_cost >= 0 AND remaining_value >= 0 AND remaining_value <= original_cost),
    -- the last of a layer always takes the last of its value, so an empty layer is worth nothing
    CONSTRAINT ck_stock_cost_layers_empty CHECK (remaining_quantity > 0 OR remaining_value = 0)
);

-- FIFO order is id order (posting order), which is stable even when two receipts share a date.
CREATE INDEX ix_stock_cost_layers_open ON stock_cost_layers (material_id, id) WHERE remaining_quantity > 0;

CREATE TABLE stock_cost_allocations (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_id            BIGINT        NOT NULL,
    material_id            BIGINT        NOT NULL,
    layer_id               BIGINT        NOT NULL,
    -- negative: taken from the layer (issue, negative adjustment); positive: put back by a return
    quantity               NUMERIC(14,3) NOT NULL,
    cost                   NUMERIC(15,2) NOT NULL,
    reverses_allocation_id BIGINT REFERENCES stock_cost_allocations (id),
    created_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_stock_cost_allocations_movement FOREIGN KEY (movement_id, material_id)
        REFERENCES stock_movements (id, material_id),
    CONSTRAINT fk_stock_cost_allocations_layer FOREIGN KEY (layer_id, material_id)
        REFERENCES stock_cost_layers (id, material_id),
    CONSTRAINT ck_stock_cost_allocations_sign CHECK (
        (quantity < 0 AND cost <= 0 AND reverses_allocation_id IS NULL)
        OR (quantity > 0 AND cost >= 0 AND reverses_allocation_id IS NOT NULL))
);

CREATE INDEX ix_stock_cost_allocations_movement ON stock_cost_allocations (movement_id);
CREATE INDEX ix_stock_cost_allocations_layer ON stock_cost_allocations (layer_id);
CREATE INDEX ix_stock_cost_allocations_reverses ON stock_cost_allocations (reverses_allocation_id);

CREATE TRIGGER trg_stock_cost_allocations_immutable BEFORE UPDATE OR DELETE ON stock_cost_allocations
    FOR EACH ROW EXECUTE FUNCTION sk_reject_change();

-- Backstop for returns: putting stock back must reverse a draw from the same layer, and all the
-- reversals of a draw together can't exceed what it took (quantity or cost). The draw row is locked,
-- so two returns racing on the same draw are checked one after the other.
CREATE FUNCTION sk_check_cost_reversal() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    drawn_qty     NUMERIC;
    drawn_cost    NUMERIC;
    drawn_layer   BIGINT;
    reversed_qty  NUMERIC;
    reversed_cost NUMERIC;
BEGIN
    IF NEW.reverses_allocation_id IS NULL THEN
        RETURN NEW;
    END IF;
    SELECT -quantity, -cost, layer_id INTO drawn_qty, drawn_cost, drawn_layer
      FROM stock_cost_allocations
     WHERE id = NEW.reverses_allocation_id AND quantity < 0
       FOR UPDATE;
    IF drawn_qty IS NULL OR drawn_layer <> NEW.layer_id THEN
        RAISE EXCEPTION 'A cost reversal must reverse a draw from the same layer'
            USING ERRCODE = 'check_violation';
    END IF;
    SELECT COALESCE(SUM(quantity), 0), COALESCE(SUM(cost), 0) INTO reversed_qty, reversed_cost
      FROM stock_cost_allocations
     WHERE reverses_allocation_id = NEW.reverses_allocation_id;
    IF reversed_qty + NEW.quantity > drawn_qty OR reversed_cost + NEW.cost > drawn_cost THEN
        RAISE EXCEPTION 'Reversal exceeds what allocation % drew', NEW.reverses_allocation_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_stock_cost_allocations_reversal BEFORE INSERT ON stock_cost_allocations
    FOR EACH ROW EXECUTE FUNCTION sk_check_cost_reversal();

-- Existing stock. The weighted-average history can't be turned into honest FIFO layers: the posted
-- issues were charged at the average, and replaying them FIFO would give different costs, i.e. rewrite
-- what projects were charged, and the layers would no longer add up to the stock value the ledger
-- records. So each material's current balance is carried forward as one LEGACY_BALANCE layer at
-- exactly the ledger's quantity and value. It is the oldest layer, used first; new receipts queue
-- behind it. Nothing posted before this migration gets allocations: those issues stay costing_method
-- WAC, and a later return against one comes back at that issue's own cost (as before) as a new
-- LEGACY_RETURN layer.
DO $$
DECLARE
    broken TEXT;
BEGIN
    -- refuse to carry forward a ledger that doesn't add up, rather than guess
    SELECT string_agg(material_id::TEXT, ', ') INTO broken
      FROM (SELECT s.material_id
              FROM stock_movements s
              JOIN (SELECT material_id, max(id) AS last_id FROM stock_movements GROUP BY material_id) l
                ON l.material_id = s.material_id
              JOIN stock_movements last ON last.id = l.last_id
             GROUP BY s.material_id, last.quantity_after, last.value_after
            HAVING sum(s.quantity_change) <> last.quantity_after
                OR sum(s.total_cost) <> last.value_after
                OR (last.quantity_after = 0 AND last.value_after <> 0)) bad;
    IF broken IS NOT NULL THEN
        RAISE EXCEPTION 'Stock ledger running balances do not reconcile for material(s) %; fix before FIFO', broken;
    END IF;

    INSERT INTO stock_cost_layers (material_id, source_movement_id, origin, layer_date, original_quantity, unit_cost,
                                   original_cost, remaining_quantity, remaining_value)
    SELECT m.material_id, m.id, 'LEGACY_BALANCE', m.movement_date, m.quantity_after,
           round(m.value_after / m.quantity_after, 4), m.value_after, m.quantity_after, m.value_after
      FROM stock_movements m
     WHERE m.id IN (SELECT max(id) FROM stock_movements GROUP BY material_id)
       AND m.quantity_after > 0
     ORDER BY m.material_id;
END;
$$;
