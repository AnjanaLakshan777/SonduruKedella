CREATE TABLE delay_deduction_terms (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id             BIGINT        NOT NULL,
    project_type           VARCHAR(20)   NOT NULL DEFAULT 'CONSTRUCTION',
    enabled                BOOLEAN       NOT NULL DEFAULT TRUE,
    contract_deadline      DATE          NOT NULL,
    rule                   VARCHAR(20)   NOT NULL,
    rate_per_day           NUMERIC(15,2),
    percent_per_week       NUMERIC(7,4),
    fixed_amount           NUMERIC(15,2),
    grace_days             INTEGER       NOT NULL DEFAULT 0,
    max_deduction          NUMERIC(15,2),
    actual_completion      DATE,
    applied_amount         NUMERIC(15,2),
    applied_on             DATE,
    applied_installment_id BIGINT,
    notes                  TEXT,
    created_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by             BIGINT REFERENCES app_users (id),
    updated_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version                BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uq_delay_deduction_terms_project UNIQUE (project_id),
    CONSTRAINT fk_delay_deduction_terms_project FOREIGN KEY (project_id, project_type) REFERENCES projects (id, project_type),
    -- The deduction can only reduce an installment of the same project.
    CONSTRAINT fk_delay_deduction_terms_installment FOREIGN KEY (applied_installment_id, project_id) REFERENCES installments (id, project_id),
    CONSTRAINT ck_delay_deduction_terms_type CHECK (project_type = 'CONSTRUCTION'),
    -- COALESCE(..., FALSE) in checks below: a NULL must fail the check, not pass it.
    CONSTRAINT ck_delay_deduction_terms_rule CHECK (COALESCE(
        (rule = 'PER_DAY' AND rate_per_day > 0)
        OR (rule = 'PERCENT_PER_WEEK' AND percent_per_week > 0)
        OR (rule = 'FIXED_AMOUNT' AND fixed_amount > 0), FALSE)),
    CONSTRAINT ck_delay_deduction_terms_grace CHECK (grace_days >= 0),
    CONSTRAINT ck_delay_deduction_terms_max CHECK (max_deduction > 0),
    CONSTRAINT ck_delay_deduction_terms_applied CHECK (COALESCE(
        (actual_completion IS NULL AND applied_amount IS NULL AND applied_on IS NULL AND applied_installment_id IS NULL)
        OR (actual_completion IS NOT NULL AND applied_amount >= 0 AND applied_on IS NOT NULL AND applied_installment_id IS NOT NULL), FALSE))
);

