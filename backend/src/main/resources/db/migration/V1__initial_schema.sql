-- Payments and advances: never deleted; once recorded only the void columns may change, and a void is final.
CREATE FUNCTION sk_guard_payment_change() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION '% rows cannot be deleted; void the payment instead', TG_TABLE_NAME
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF OLD.voided_at IS NOT NULL
       OR (to_jsonb(NEW) - ARRAY['voided_at', 'void_reason', 'updated_at', 'version'])
          <> (to_jsonb(OLD) - ARRAY['voided_at', 'void_reason', 'updated_at', 'version']) THEN
        RAISE EXCEPTION '% rows cannot be changed except to void them', TG_TABLE_NAME
            USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END;
$$;

