-- Sonduru Kedella: initial schema (docs/DATABASE.md, schema v2).
-- Money NUMERIC(15,2), percentages NUMERIC(7,4), quantities NUMERIC(14,3), unit costs NUMERIC(15,4).
-- Foreign keys use the default NO ACTION: financial records are never removed by cascade.

-- =====================================================================
-- Settings and shared tables
-- =====================================================================

CREATE TABLE app_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(100) NOT NULL,
    display_name  VARCHAR(150) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_app_users_username UNIQUE (username)
);

CREATE TABLE payment_methods (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(50) NOT NULL,
    active     BOOLEAN     NOT NULL DEFAULT TRUE,
    sort_order INTEGER     NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by BIGINT REFERENCES app_users (id),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version    BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uq_payment_methods_name UNIQUE (name)
);

CREATE TABLE units (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(30) NOT NULL,
    active     BOOLEAN     NOT NULL DEFAULT TRUE,
    sort_order INTEGER     NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by BIGINT REFERENCES app_users (id),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version    BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uq_units_name UNIQUE (name)
);

CREATE TABLE expense_categories (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_group    VARCHAR(20)  NOT NULL,
    name             VARCHAR(100) NOT NULL,
    locked           BOOLEAN      NOT NULL DEFAULT FALSE,
    system_generated BOOLEAN      NOT NULL DEFAULT FALSE,
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order       INTEGER      NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by       BIGINT REFERENCES app_users (id),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_expense_categories_group CHECK (expense_group IN ('DESIGN', 'CONSTRUCTION', 'CONSULTATION', 'COMPANY')),
    CONSTRAINT ck_expense_categories_system_locked CHECK (NOT system_generated OR locked),
    CONSTRAINT uq_expense_categories_group_name UNIQUE (expense_group, name),
    -- Target of the composite key that keeps system-generated categories out of manual expenses.
    CONSTRAINT uq_expense_categories_guard UNIQUE (id, expense_group, system_generated)
);

CREATE TABLE company_profile (
    id                         SMALLINT     PRIMARY KEY DEFAULT 1,
    name                       VARCHAR(200) NOT NULL,
    tagline                    VARCHAR(200),
    address                    VARCHAR(300),
    phone                      VARCHAR(30),
    email                      VARCHAR(150),
    registration_no            VARCHAR(50),
    owner_name                 VARCHAR(150),
    financial_year_start_month SMALLINT     NOT NULL DEFAULT 4,
    supplier_credit_days       INTEGER      NOT NULL DEFAULT 14,
    created_at                 TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by                 BIGINT REFERENCES app_users (id),
    updated_at                 TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version                    BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_company_profile_single_row CHECK (id = 1),
    CONSTRAINT ck_company_profile_fy_month CHECK (financial_year_start_month BETWEEN 1 AND 12),
    CONSTRAINT ck_company_profile_credit_days CHECK (supplier_credit_days >= 0)
);

CREATE TABLE commission_policy (
    id                         SMALLINT     PRIMARY KEY DEFAULT 1,
    design_commission_pool_pct NUMERIC(7,4) NOT NULL DEFAULT 20,
    construction_warning_pct   NUMERIC(7,4),
    created_at                 TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by                 BIGINT REFERENCES app_users (id),
    updated_at                 TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version                    BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_commission_policy_single_row CHECK (id = 1),
    CONSTRAINT ck_commission_policy_design_pool CHECK (design_commission_pool_pct > 0 AND design_commission_pool_pct < 100),
    CONSTRAINT ck_commission_policy_construction CHECK (construction_warning_pct > 0 AND construction_warning_pct < 100)
);

CREATE TABLE wage_settings (
    id                  SMALLINT      PRIMARY KEY DEFAULT 1,
    default_daily_wage  NUMERIC(15,2) NOT NULL,
    hours_per_day       NUMERIC(4,2)  NOT NULL DEFAULT 8,
    overtime_multiplier NUMERIC(5,2)  NOT NULL DEFAULT 1.5,
    payday              VARCHAR(10)   NOT NULL DEFAULT 'SATURDAY',
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by          BIGINT REFERENCES app_users (id),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version             BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ck_wage_settings_single_row CHECK (id = 1),
    CONSTRAINT ck_wage_settings_daily_wage CHECK (default_daily_wage > 0),
    CONSTRAINT ck_wage_settings_hours CHECK (hours_per_day > 0 AND hours_per_day <= 12),
    CONSTRAINT ck_wage_settings_multiplier CHECK (overtime_multiplier > 0),
    CONSTRAINT ck_wage_settings_payday CHECK (payday IN ('FRIDAY', 'SATURDAY'))
);

