CREATE TABLE projects (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(30)   NOT NULL,
    name                VARCHAR(200)  NOT NULL,
    client_id           BIGINT        NOT NULL REFERENCES clients (id),
    project_type        VARCHAR(20)   NOT NULL,
    location            VARCHAR(200),
    description         TEXT,
    contract_value      NUMERIC(15,2) NOT NULL,
    start_date          DATE          NOT NULL,
    expected_completion DATE          NOT NULL,
    actual_completion   DATE,
    status              VARCHAR(20)   NOT NULL DEFAULT 'PLANNING',
    notes               TEXT,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by          BIGINT REFERENCES app_users (id),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version             BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uq_projects_code UNIQUE (code),
    -- Target of composite keys that restrict child records to certain project types.
    CONSTRAINT uq_projects_id_type UNIQUE (id, project_type),
    CONSTRAINT ck_projects_type CHECK (project_type IN ('DESIGN', 'CONSTRUCTION', 'CONSULTATION')),
    CONSTRAINT ck_projects_status CHECK (status IN ('PLANNING', 'IN_PROGRESS', 'ON_HOLD', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_projects_contract_value CHECK (contract_value > 0 OR (project_type = 'CONSULTATION' AND contract_value >= 0)),
    CONSTRAINT ck_projects_dates CHECK (expected_completion > start_date)
);

CREATE TABLE project_agreements (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id        BIGINT       NOT NULL REFERENCES projects (id),
    original_filename VARCHAR(255) NOT NULL,
    content_type      VARCHAR(100) NOT NULL,
    size_bytes        BIGINT       NOT NULL,
    sha256            CHAR(64)     NOT NULL,
    storage_key       VARCHAR(500) NOT NULL,
    uploaded_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    removed_at        TIMESTAMPTZ,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by        BIGINT REFERENCES app_users (id),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_project_agreements_storage_key UNIQUE (storage_key),
    CONSTRAINT ck_project_agreements_pdf CHECK (content_type = 'application/pdf'),
    CONSTRAINT ck_project_agreements_size CHECK (size_bytes > 0)
);

CREATE UNIQUE INDEX uq_project_agreements_current ON project_agreements (project_id) WHERE removed_at IS NULL;

