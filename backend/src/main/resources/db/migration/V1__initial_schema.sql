-- Append-only ledger: no updated_at or version (rows are never changed).
CREATE TABLE stock_movements (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id               BIGINT        NOT NULL REFERENCES materials (id),
    movement_date             DATE          NOT NULL,
    movement_type             VARCHAR(20)   NOT NULL,
    quantity_change           NUMERIC(14,3) NOT NULL,
    unit_cost                 NUMERIC(15,4) NOT NULL,
    total_cost                NUMERIC(15,2) NOT NULL,
    quantity_after            NUMERIC(14,3) NOT NULL,
    value_after               NUMERIC(15,2) NOT NULL,
    project_id                BIGINT REFERENCES projects (id),
    supplier_invoice_line_id  BIGINT,
    invoice_allocation        VARCHAR(10),
    returned_from_movement_id BIGINT,
    reason                    TEXT,
    reference                 VARCHAR(100),
    created_at                TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by                BIGINT REFERENCES app_users (id),
    CONSTRAINT ck_stock_movements_type CHECK (movement_type IN ('RECEIVED', 'ISSUED', 'RETURNED', 'ADJUSTMENT')),
    CONSTRAINT ck_stock_movements_sign CHECK (
        (movement_type IN ('RECEIVED', 'RETURNED') AND quantity_change > 0)
        OR (movement_type = 'ISSUED' AND quantity_change < 0)
        OR (movement_type = 'ADJUSTMENT' AND quantity_change <> 0 AND reason IS NOT NULL AND btrim(reason) <> '')),
    CONSTRAINT ck_stock_movements_cost_sign CHECK (
        (quantity_change > 0 AND total_cost >= 0) OR (quantity_change < 0 AND total_cost <= 0)),
    CONSTRAINT ck_stock_movements_unit_cost CHECK (unit_cost >= 0),
    CONSTRAINT ck_stock_movements_balance CHECK (quantity_after >= 0 AND value_after >= 0),
    CONSTRAINT ck_stock_movements_project CHECK ((project_id IS NOT NULL) = (movement_type IN ('ISSUED', 'RETURNED'))),
    CONSTRAINT ck_stock_movements_return_link CHECK ((returned_from_movement_id IS NOT NULL) = (movement_type = 'RETURNED')),
    CONSTRAINT ck_stock_movements_invoice_line CHECK (COALESCE(
        (supplier_invoice_line_id IS NULL AND invoice_allocation IS NULL)
        OR (supplier_invoice_line_id IS NOT NULL AND movement_type = 'RECEIVED' AND invoice_allocation = 'STOCK'), FALSE)),
    -- One receipt per invoice line, for the line's own material, and only from STOCK invoices.
