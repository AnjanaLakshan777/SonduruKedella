-- A return must reference an ISSUED movement and cannot exceed what is still un-returned on it.
CREATE FUNCTION sk_check_stock_return() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    issued_qty   NUMERIC;
    returned_qty NUMERIC;
BEGIN
    IF NEW.movement_type <> 'RETURNED' THEN
        RETURN NEW;
    END IF;
    SELECT -quantity_change INTO issued_qty
      FROM stock_movements
     WHERE id = NEW.returned_from_movement_id AND movement_type = 'ISSUED'
       FOR UPDATE;
    IF issued_qty IS NULL THEN
        RAISE EXCEPTION 'A return must reference an ISSUED stock movement'
            USING ERRCODE = 'check_violation';
    END IF;
    SELECT COALESCE(SUM(quantity_change), 0) INTO returned_qty
      FROM stock_movements
     WHERE returned_from_movement_id = NEW.returned_from_movement_id;
    IF returned_qty + NEW.quantity_change > issued_qty THEN
        RAISE EXCEPTION 'Return quantity exceeds the quantity still un-returned on issue %', NEW.returned_from_movement_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_stock_movements_return BEFORE INSERT ON stock_movements
    FOR EACH ROW EXECUTE FUNCTION sk_check_stock_return();

-- Payroll freeze: once an employee's week has a payroll line, that employee's attendance,
-- overtime and adjustment for the week cannot be inserted, changed or deleted.
CREATE FUNCTION sk_payroll_week_frozen(p_employee_id BIGINT, p_day DATE) RETURNS boolean
LANGUAGE sql STABLE AS $$
    SELECT EXISTS (
        SELECT 1 FROM payroll_lines
         WHERE employee_id = p_employee_id
           AND week_start = p_day - (EXTRACT(ISODOW FROM p_day)::int - 1)
    );
$$;

CREATE FUNCTION sk_guard_frozen_payroll_week() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    day_column TEXT := CASE WHEN TG_TABLE_NAME = 'payroll_adjustments' THEN 'week_start' ELSE 'work_date' END;
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE')
       AND sk_payroll_week_frozen(OLD.employee_id, (to_jsonb(OLD) ->> day_column)::date) THEN
        RAISE EXCEPTION 'Payroll week is frozen for employee %; record a payroll correction instead', OLD.employee_id
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF TG_OP IN ('INSERT', 'UPDATE')
       AND sk_payroll_week_frozen(NEW.employee_id, (to_jsonb(NEW) ->> day_column)::date) THEN
        RAISE EXCEPTION 'Payroll week is frozen for employee %; record a payroll correction instead', NEW.employee_id
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_attendance_frozen BEFORE INSERT OR UPDATE OR DELETE ON attendance
    FOR EACH ROW EXECUTE FUNCTION sk_guard_frozen_payroll_week();
CREATE TRIGGER trg_overtime_entries_frozen BEFORE INSERT OR UPDATE OR DELETE ON overtime_entries
    FOR EACH ROW EXECUTE FUNCTION sk_guard_frozen_payroll_week();
CREATE TRIGGER trg_payroll_adjustments_frozen BEFORE INSERT OR UPDATE OR DELETE ON payroll_adjustments
