-- =====================================================================
-- V11: custom roles.
-- A Super Admin names a role (Supervisor, Auditor, ...) and picks the pages it can open.
-- Users on a custom role get role = 'CUSTOM' and point at it. Additive: existing users keep
-- SUPER_ADMIN or ADMIN and no custom role.
-- =====================================================================

CREATE TABLE custom_roles (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(50) NOT NULL,
    version    BIGINT      NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_custom_roles_name CHECK (name = btrim(name) AND name <> '')
);

-- "Auditor" and "auditor" are the same role
CREATE UNIQUE INDEX uq_custom_roles_name_lower ON custom_roles (lower(name));

-- the pages a role can open; same names as the AppPage enum
CREATE TABLE custom_role_pages (
    role_id BIGINT      NOT NULL REFERENCES custom_roles (id) ON DELETE CASCADE,
    page    VARCHAR(30) NOT NULL,
    PRIMARY KEY (role_id, page),
    CONSTRAINT ck_custom_role_pages_page CHECK (page IN (
        'DASHBOARD', 'PROJECTS', 'CLIENTS', 'REVENUE', 'EXPENSES', 'COMMISSIONS', 'REPORTS',
        'SUPPLIERS', 'INVENTORY', 'LABOUR', 'SETTINGS'))
);

-- a role in use can't be deleted (no ON DELETE here on purpose)
ALTER TABLE app_users ADD COLUMN custom_role_id BIGINT REFERENCES custom_roles (id);

ALTER TABLE app_users DROP CONSTRAINT ck_app_users_role;
ALTER TABLE app_users
    ADD CONSTRAINT ck_app_users_role CHECK (role IN ('SUPER_ADMIN', 'ADMIN', 'CUSTOM')),
    ADD CONSTRAINT ck_app_users_custom_role CHECK ((role = 'CUSTOM') = (custom_role_id IS NOT NULL));

CREATE INDEX ix_app_users_custom_role ON app_users (custom_role_id);

ALTER TABLE security_events DROP CONSTRAINT ck_security_events_type;
ALTER TABLE security_events ADD CONSTRAINT ck_security_events_type CHECK (event_type IN (
    'LOGIN_SUCCEEDED', 'LOGIN_FAILED', 'LOGIN_THROTTLED', 'LOGOUT',
    'USER_CREATED', 'USER_UPDATED', 'ROLE_CHANGED', 'USER_ACTIVATED', 'USER_DEACTIVATED',
    'PASSWORD_CHANGED', 'PASSWORD_RESET', 'SUPER_ADMIN_BOOTSTRAPPED',
    'CUSTOM_ROLE_CREATED', 'CUSTOM_ROLE_UPDATED', 'CUSTOM_ROLE_DELETED'));
