-- =====================================================================
-- V5: application roles on app_users, and the security audit trail.
--
-- Additive only. Any app_users row that already exists becomes ADMIN (the lower role); nobody is
-- made SUPER_ADMIN by this migration. The first Super Admin is provisioned at startup from
-- environment variables, never from SQL (see DEVELOPMENT_WORKFLOW.md).
-- =====================================================================

-- role: the only two application roles. auth_version is bumped whenever a user's access changes
-- (deactivated, role changed, password changed or reset); a session remembers the value it signed
-- in with, and is dropped on its next request once they differ.
ALTER TABLE app_users
    ADD COLUMN role         VARCHAR(20) NOT NULL DEFAULT 'ADMIN',
    ADD COLUMN auth_version BIGINT      NOT NULL DEFAULT 0;

-- The default only existed to fill rows that were already there; new users must name their role.
ALTER TABLE app_users ALTER COLUMN role DROP DEFAULT;

ALTER TABLE app_users
    ADD CONSTRAINT ck_app_users_role CHECK (role IN ('SUPER_ADMIN', 'ADMIN')),
    ADD CONSTRAINT ck_app_users_auth_version CHECK (auth_version >= 0);

-- The application stores usernames in lower case; this stops "Kamal" and "kamal" both existing
-- if anything ever writes the table directly.
CREATE UNIQUE INDEX uq_app_users_username_lower ON app_users (lower(username));

-- The "last active Super Admin" check reads exactly these rows.
CREATE INDEX ix_app_users_active_super_admins ON app_users (id) WHERE role = 'SUPER_ADMIN' AND enabled;

-- Security-sensitive actions: sign-ins (successful, failed and throttled), sign-outs, and every
-- change to a user account. Never holds a password, hash or session id. Append-only.
CREATE TABLE security_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type     VARCHAR(40)  NOT NULL,
    -- who did it (null for failed or throttled sign-ins and the startup bootstrap)
    actor_user_id  BIGINT REFERENCES app_users (id),
    -- whose account it was about (null when the typed username matched nobody)
    target_user_id BIGINT REFERENCES app_users (id),
    -- the username as typed at sign-in, kept for failed attempts
    username       VARCHAR(100),
    remote_address VARCHAR(45),
    details        VARCHAR(300),
    occurred_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_security_events_type CHECK (event_type IN (
        'LOGIN_SUCCEEDED', 'LOGIN_FAILED', 'LOGIN_THROTTLED', 'LOGOUT',
        'USER_CREATED', 'USER_UPDATED', 'ROLE_CHANGED', 'USER_ACTIVATED', 'USER_DEACTIVATED',
        'PASSWORD_CHANGED', 'PASSWORD_RESET', 'SUPER_ADMIN_BOOTSTRAPPED'))
);

CREATE INDEX ix_security_events_occurred_at ON security_events (occurred_at);
CREATE INDEX ix_security_events_actor ON security_events (actor_user_id);
CREATE INDEX ix_security_events_target ON security_events (target_user_id);

-- Same guard as the other append-only ledgers (sk_reject_change is defined in V1).
CREATE TRIGGER trg_security_events_immutable BEFORE UPDATE OR DELETE ON security_events
    FOR EACH ROW EXECUTE FUNCTION sk_reject_change();
