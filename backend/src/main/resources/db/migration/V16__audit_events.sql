-- =====================================================================
-- V16: audit history (owner request 2026-11-15, Super Admin only).
-- One row per record created, changed or deleted through the application: who, when, from which
-- request, and for a change the old and new value of each field. Append-only, like security_events.
-- Passwords and session counters are never stored (the application masks or skips them).
-- =====================================================================

CREATE TABLE audit_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- null when nobody was signed in (startup tasks)
    user_id     BIGINT REFERENCES app_users (id),
    -- the name at the time, so the row still reads right after a rename
    username    VARCHAR(100),
    -- the request that made the change, e.g. POST /api/v1/projects/7/receipts
    http_method VARCHAR(10),
    path        VARCHAR(300),
    -- groups the rows one request wrote
    request_id  UUID,
    entity_type VARCHAR(60)  NOT NULL,
    entity_id   VARCHAR(40),
    change_type VARCHAR(10)  NOT NULL,
    -- {"field": [old, new]}; on create old is null, on delete new is null
    changes     JSONB        NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT ck_audit_events_change_type CHECK (change_type IN ('CREATED', 'UPDATED', 'DELETED'))
);

CREATE INDEX ix_audit_events_occurred_at ON audit_events (occurred_at);
CREATE INDEX ix_audit_events_user ON audit_events (user_id);
CREATE INDEX ix_audit_events_entity ON audit_events (entity_type, entity_id);

-- same guard as the other append-only tables (sk_reject_change is defined in V1)
CREATE TRIGGER trg_audit_events_immutable BEFORE UPDATE OR DELETE ON audit_events
    FOR EACH ROW EXECUTE FUNCTION sk_reject_change();
