package com.sondurukedella.settings.service;

import com.sondurukedella.common.exception.BusinessRuleException;
import com.sondurukedella.common.exception.ConflictException;
import com.sondurukedella.common.exception.NotFoundException;
import com.sondurukedella.settings.dto.ExpenseCategoryCreateRequest;
import com.sondurukedella.settings.dto.ExpenseCategoryResponse;
import com.sondurukedella.settings.entity.ExpenseCategory;
import com.sondurukedella.settings.entity.ExpenseGroup;
import com.sondurukedella.settings.mapper.SettingsMapper;
import com.sondurukedella.settings.repository.ExpenseCategoryRepository;
import com.sondurukedella.settings.validation.SettingsText;
import java.util.List;
import java.util.Optional;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

/**
 * Expense categories per work type. Users can add and remove their own categories; the locked ones
 * (Materials, Labour, Commission) cannot be removed. Removed categories are deactivated so existing
 * expenses keep their category, and re-adding the name reactivates it.
 */
@Service
@RequiredArgsConstructor
public class ExpenseCategoryService {

    private final ExpenseCategoryRepository repository;
    private final SettingsMapper mapper;

    @Transactional(readOnly = true)
    public List<ExpenseCategoryResponse> listActive(ExpenseGroup group) {
        List<ExpenseCategory> categories = group == null
                ? repository.findByActiveTrueOrderByExpenseGroupAscSortOrderAscIdAsc()
                : repository.findByExpenseGroupAndActiveTrueOrderBySortOrderAscIdAsc(group);
        return categories.stream().map(mapper::toResponse).toList();
    }

    @Transactional
    public LookupAddResult<ExpenseCategoryResponse> add(ExpenseCategoryCreateRequest request) {
        String name = SettingsText.requireName(request.name(), ExpenseCategory.NAME_MAX_LENGTH);
        Optional<ExpenseCategory> existing = repository.findByExpenseGroupAndNameIgnoreCase(request.group(), name);
        if (existing.isPresent()) {
            ExpenseCategory category = existing.get();
            if (category.isActive()) {
                throw new ConflictException("\"" + name + "\" is already in the list.");
            }
            category.setName(name);
            category.setActive(true);
            return new LookupAddResult<>(mapper.toResponse(repository.saveAndFlush(category)), false);
        }
        ExpenseCategory created = new ExpenseCategory(request.group(), name,
                repository.findMaxSortOrder(request.group()) + 1);
        return new LookupAddResult<>(mapper.toResponse(repository.saveAndFlush(created)), true);
    }

    @Transactional
    public void deactivate(long id) {
        ExpenseCategory category = repository.findById(id)
                .orElseThrow(() -> new NotFoundException("Expense category not found."));
        if (category.isLocked()) {
            throw new BusinessRuleException("\"" + category.getName()
                    + "\" is generated by other modules and cannot be removed.");
        }
        if (category.isActive()) {
            category.setActive(false);
            repository.saveAndFlush(category);
        }
    }
}
